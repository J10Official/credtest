"""
Module for handling interactions with the Gemini API.
Handles configuration, model initialization, retries, and rate limiting.
"""
import google.generativeai as genai
from config import API_KEY, MODEL_NAME
import time

# Configure the API
genai.configure(api_key=API_KEY)
model = genai.GenerativeModel(MODEL_NAME)

# Set to True to enable test mode (returns dummy text without API calls)
TEST_MODE = False

def generate_content(contents, retries: int = 3) -> str:
    """
    Generates content using the Gemini API.
    
    Args:
        contents: The prompt(s) to send to the model. Can be a string or a list (e.g., [prompt, image]).
        retries (int): Number of retries for API errors.
        
    Returns:
        str: The generated text, or None if generation fails after all retries.
    """
    if TEST_MODE:
        return "this text is not generated by the api"

    retry_delays = [10, 20, 30, 60, 60]
    for attempt in range(len(retry_delays)):
        try:
            response = model.generate_content(contents)
            if response.text:
                return response.text
        except Exception as e:
            print(f"API Error (attempt {attempt+1}/{len(retry_delays)}): {e}")
            wait_time = retry_delays[attempt]
            print(f"Waiting {wait_time} seconds before retrying...")
            time.sleep(wait_time)
    return None
